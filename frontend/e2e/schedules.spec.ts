test('accepted cancellation stays pending until the job ends', async ({ page }) => {
  await page.goto('/e2e/fixture.html?scenario=schedules&cancelPending=1')
  await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
  await page.getByRole('button', { name: 'Abrir projeto' }).click()
  await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Agendamentos' }).click()
  await page.getByLabel('Nome do agendamento').fill('Revisão')
  await page.getByRole('textbox', { name: 'Prompt', exact: true }).fill('Revise')
  await page.getByRole('button', { name: 'Salvar agendamento' }).click()
  await page.getByRole('button', { name: 'Executar agora Revisão' }).click()
  await page.getByRole('button', { name: 'Cancelar job' }).click()
  await expect(page.getByText('Cancelamento solicitado', { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('aguardando confirmação')
  await expect(page.getByText('Job cancelado.')).toHaveCount(0)
})
