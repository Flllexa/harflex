import { expect, test } from './locale'
import { checkboxSentence, stretchedChecks } from './targets'

for (const width of [320, 768, 900, 1024, 1440]) {
  test(`Coder session opens from the Code phase at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/e2e/fixture.html?scenario=pipeline-code')
    await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
    await page.getByRole('button', { name: 'Abrir projeto' }).click()
    if (width < 768) await page.getByRole('button', { name: 'Abrir navegação' }).click()
    await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Pipelines' }).click()
    await expect(page.getByRole('navigation', { name: 'SDD Pipeline' }).locator('[aria-current="step"]')).toContainText('Code')
    await expect(page.getByRole('combobox', { name: 'Modelo da fase Code' })).toHaveValue('Modelo API')
    const executeCoder = page.getByRole('button', { name: 'Executar Coder' })
    await executeCoder.scrollIntoViewIfNeeded()
    await expect(executeCoder).toBeInViewport()
    if (width >= 1440) {
      const location = await executeCoder.boundingBox()
      expect(location && location.y + location.height).toBeLessThan(900)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: info.outputPath(`code-${width}.png`), fullPage: true })
    await executeCoder.click()
    await expect(page.getByLabel('Mensagem')).toBeVisible()
    if (width < 768) await page.getByRole('button', { name: 'Abrir navegação' }).click()
    await expect(page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Conversas' })).toHaveAttribute('aria-current', 'page')
    if (width < 768) await page.keyboard.press('Escape')
    await expect(page.getByRole('group', { name: 'Aprovação necessária' })).toBeVisible()
    await page.getByRole('tab', { name: 'Artefatos' }).click()
    await page.getByRole('group', { name: 'Tipo de artefato' }).getByRole('button', { name: 'SPEC', exact: true }).click()
    await expect(page.getByText('Critério: CSV correto')).toBeVisible()
  })
}

// The confirmation box once inherited the text-field sizing (full row, 44px tall), which squeezed its
// sentence into a column one letter wide and pushed the action buttons thousands of pixels down.
for (const width of [320, 768, 1440]) {
  test(`the copy confirmation keeps a small box and a readable sentence at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/e2e/fixture.html?scenario=pipeline-code-cli')
    await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
    await page.getByRole('button', { name: 'Abrir projeto' }).click()
    if (width < 768) await page.getByRole('button', { name: 'Abrir navegação' }).click()
    await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Pipelines' }).click()
    await page.getByTestId('picker-pipeline-backend').getByRole('button').click()
    await page.getByRole('option', { name: 'Local API' }).click()
    const confirm = page.getByRole('checkbox', { name: /Confirmo copiar estes arquivos/i })
    await confirm.scrollIntoViewIfNeeded()
    const box = await confirm.boundingBox()
    expect(box!.width).toBeLessThanOrEqual(24)
    expect(box!.height).toBeLessThanOrEqual(24)
    const sentence = await checkboxSentence(page, /Confirmo copiar estes arquivos/i)
    expect(sentence.width).toBeGreaterThanOrEqual(150)
    expect(sentence.lines).toBeLessThanOrEqual(4)
    expect(await stretchedChecks(page)).toEqual([])
    // Both actions stay a short scroll away rather than below a wall of letters: the button sits within a screen of the box, wherever the page happens to start.
    const action = await page.getByRole('button', { name: 'Executar Coder' }).boundingBox()
    expect(action!.y - box!.y).toBeLessThan(400)
    await page.getByRole('button', { name: 'Executar Coder' }).scrollIntoViewIfNeeded()
    await expect(page.getByRole('button', { name: 'Executar Coder' })).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: info.outputPath(`copy-confirmation-${width}.png`) })
  })
}

