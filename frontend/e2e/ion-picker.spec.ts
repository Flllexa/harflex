for (const width of [320, 1024]) {
  test(`searchable picker has one visible keyboard focus ring at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/e2e/ion-picker.html')
    const picker = page.getByTestId('picker-browser-document')
    const search = picker.getByRole('combobox')
    await search.fill('plataforma')
    await expect(page.getByRole('option', { name: /docs\/plataforma\/fluxos-e-integracoes/ })).toBeVisible()
    const focus = await picker.evaluate(element => {
      const input = element.querySelector<HTMLInputElement>('.ion-picker-input')!
      const group = element.querySelector<HTMLElement>('.ion-picker-group')!
      return {
        inputOutlineWidth: getComputedStyle(input).outlineWidth,
        groupOutlineWidth: getComputedStyle(group).outlineWidth,
        groupOutlineStyle: getComputedStyle(group).outlineStyle,
        groupOutlineColor: getComputedStyle(group).outlineColor,
      }
    })
    expect(focus.groupOutlineStyle).toBe('solid')
    expect(focus.groupOutlineWidth).toBe('2px')
    expect(focus.groupOutlineColor).toBe('rgb(92, 242, 166)')
    expect(focus.inputOutlineWidth).toBe('0px')
    await page.screenshot({ path: info.outputPath(`ion-picker-single-focus-${width}.png`) })
  })
}

test('ComboBox mantém valor vazio e texto coerentes no Chromium', async ({ page }) => {
  await page.goto('/e2e/ion-picker.html')
  const input = page.getByRole('combobox', { name: 'Documento' })
  const selected = page.getByTestId('selected-value')
  await expect(input).toHaveValue('Código')

  await page.getByTestId('picker-browser-document').locator('.ion-picker-chevron').click()
  await page.getByRole('option', { name: 'Todos os documentos' }).click()
  await expect(selected).toHaveText('vazio')
  await expect(input).toHaveValue('Todos os documentos')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await page.getByTestId('picker-browser-document').locator('.ion-picker-chevron').click()
  await expect(page.getByRole('option', { name: 'Arquitetura' })).toBeVisible()
  await page.keyboard.press('Escape')

  await input.fill('arq')
  await expect(selected).toHaveText('vazio')
  await expect(page.getByRole('option', { name: 'Arquitetura' })).toBeVisible()
  await page.getByRole('option', { name: 'Arquitetura' }).click()
  await expect(selected).toHaveText('a')
  await expect(input).toHaveValue('Arquitetura')

  await input.fill('')
  await expect(selected).toHaveText('vazio')
  await expect(input).toHaveValue('')
  await input.blur()
  await expect(input).not.toHaveValue('Arquitetura')
})

test('workflow obrigatório só permite enviar uma opção selecionada', async ({ page }) => {
  await page.goto('/e2e/ion-picker.html')
  const form = page.getByTestId('required-form')
  const input = form.getByRole('combobox', { name: 'Workflow' })
  const selected = page.getByTestId('workflow-value')
  const submissions = page.getByTestId('workflow-submissions')
  await expect(input).toHaveValue('Workflow B')

  await form.getByRole('button', { name: 'Reset workflow' }).click()
  await expect(selected).toHaveText('vazio')
  await expect(input).toHaveValue('')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(false)
  await form.getByRole('button', { name: 'Salvar workflow' }).click()
  await expect(submissions).toHaveText('0')

  await input.fill('inexistente')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(false)
  await form.evaluate(element => (element as HTMLFormElement).requestSubmit())
  await expect(submissions).toHaveText('0')
  await page.keyboard.press('Escape')

  await input.fill('Workflow')
  await page.getByRole('option', { name: 'Workflow B' }).click()
  await expect(selected).toHaveText('b')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(true)
  await form.getByRole('button', { name: 'Salvar workflow' }).click()
  await expect(submissions).toHaveText('1')

  await form.locator('.ion-picker-chevron').click()
  await page.getByRole('option', { name: 'Escolha workflow' }).click()
  await expect(selected).toHaveText('vazio')
  await expect(input).toHaveValue('')
  expect(await form.evaluate(element => (element as HTMLFormElement).checkValidity())).toBe(false)
  await page.keyboard.press('Escape')
  await form.getByRole('button', { name: 'Salvar workflow' }).click()
  await expect(submissions).toHaveText('1')
})
