import { expect, test, type Page } from './locale'

async function settleScroll(page: Page) {
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
}

for (const width of [320, 768, 900, 1024, 1440]) {
  test(`Ion picker preserves geometry and dialog focus at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/e2e/fixture.html?scenario=settings')
    await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
    await page.getByRole('button', { name: 'Abrir projeto' }).click()
    if (width < 768) await page.getByRole('button', { name: 'Abrir navegação' }).click()
    await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Configurações' }).click()
    const opener = page.getByRole('button', { name: 'Adicionar provedor' })
    await opener.click()
    const dialog = page.getByRole('dialog', { name: 'Configurar provedor' })
    const trigger = page.getByTestId('picker-provider-type').getByRole('button')
    await expect(trigger).toHaveAccessibleName(/Tipo de provedor/)
    await trigger.scrollIntoViewIfNeeded()
    await settleScroll(page)
    expect((await trigger.boundingBox())?.height).toBe(48)
    await trigger.click()
    const list = page.getByRole('listbox')
    await expect(list).toBeVisible()
    expect((await page.getByRole('option', { name: 'LM Studio local' }).boundingBox())?.height ?? 0).toBeGreaterThanOrEqual(44)
    const popover = page.locator('[data-ion-picker-popover]')
    const bounds = await popover.boundingBox()
    expect(bounds).not.toBeNull()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900)
    await page.keyboard.press('End')
    await expect(page.getByRole('option', { name: 'Ollama local' })).toHaveAttribute('data-focused', 'true')
    await page.keyboard.press('Home')
    await expect(page.getByRole('option', { name: 'API compatível' })).toHaveAttribute('data-focused', 'true')
    await page.screenshot({ path: info.outputPath(`ion-picker-list-${width}.png`) })
    await page.keyboard.press('Escape')
    await expect(list).not.toBeVisible()
    await expect(dialog).toBeVisible()
    await expect(trigger).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByLabel('URL base')).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    await expect(trigger).toContainText('Ollama local')
    await trigger.click()
    await page.getByRole('option', { name: 'LM Studio local' }).click()
    await expect(trigger).toContainText('LM Studio local')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ path: info.outputPath(`ion-picker-selected-${width}.png`), fullPage: true })
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(opener).toBeFocused()
  })
}

test('long timezone search retains only chosen value at 320px and reduced motion', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/e2e/fixture.html?scenario=schedules')
  await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
  await page.getByRole('button', { name: 'Abrir projeto' }).click()
  await page.getByRole('button', { name: 'Abrir navegação' }).click()
  await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Agendamentos' }).click()
  const search = page.getByTestId('picker-schedule-timezone').getByRole('combobox')
  await search.scrollIntoViewIfNeeded()
  await settleScroll(page)
  await search.fill('')
  await expect(page.getByRole('listbox')).toBeVisible()
  expect(await page.getByRole('option').count()).toBeGreaterThan(10)
  await page.screenshot({ path: info.outputPath('ion-picker-timezone-list-320.png') })
  await search.fill('timezone-not-found')
  await expect(page.getByText('Nenhuma opção encontrada.')).toBeVisible()
  await search.fill('America/Sao_Paulo')
  await expect(page.getByRole('option', { name: 'America/Sao_Paulo', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('ion-picker-timezone-filter-320.png') })
  await page.getByRole('option', { name: 'America/Sao_Paulo', exact: true }).click()
  await expect(search).toHaveValue('America/Sao_Paulo')
  await search.focus()
  await page.keyboard.press('ArrowDown')
  const popover = page.locator('[data-ion-picker-popover]')
  await expect(popover).toBeVisible()
  expect(await popover.evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  await page.keyboard.press('Escape')
  await expect(popover).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

