import { expect, test } from '@playwright/test'

const providerName = 'API de testes financeiros com identificação extensa'
const modelName = 'Modelo de teste com descrição longa para validar truncamento responsivo'

test('shows a recovery path instead of empty provider selectors when Codex is the only default', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/e2e/fixture.html?scenario=sdd-authoring-no-api')
  await page.getByLabel('Caminho da pasta').fill('/synthetic/workspace/api-faturas')
  await page.getByRole('button', { name: 'Abrir projeto' }).click()
  await page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Pipelines' }).click()
  await page.getByLabel('Discovery', { exact: true }).fill('Criar um TODO sem rede e persistir no navegador.')
  await page.getByRole('button', { name: 'Criar pipeline' }).click()

  const recovery = page.getByRole('alert').filter({ hasText: 'Este pipeline precisa de um executor disponível' })
  await expect(recovery).toContainText('Este pipeline precisa de um executor disponível')
  await expect(recovery).toContainText('Codex CLI está configurado para Conversas')
  await expect(page.getByRole('combobox', { name: 'Provedor desta etapa' })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Modelo' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Concluir Discovery e iniciar brainstorming' })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('professional-no-api-recovery.png'), fullPage: true })
  await page.getByRole('button', { name: 'Configurar provedor API' }).click()
  await expect(page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Configurações' })).toHaveAttribute('aria-current', 'page')
})

