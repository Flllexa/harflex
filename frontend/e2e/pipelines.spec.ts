  await page.getByRole('option', { name: modelName }).click()
  await page.getByTestId('picker-authoring-stage-effort-spec').locator('button').click()
  await page.getByRole('option', { name: 'high' }).click()
  await page.getByRole('button', { name: 'Salvar preferência' }).click()
