  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(modelMode).toContainText('Escolher para esta fase')
  await page.getByTestId('picker-authoring-stage-provider-spec').locator('button').click()
  await page.getByRole('option', { name: providerName }).click()
